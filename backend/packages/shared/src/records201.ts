/** Condition for IF_APPLICABLE items, checked against the employee record. */
export type Applicability = 'MARRIED' | 'HAS_CHILDREN' | 'LICENSED' | 'PRIOR_EMPLOYER_THIS_YEAR';

export interface DocumentTypeDef {
  code: DocumentType;
  section: DocSection;
  /** Short label for lists, in plain HR language. */
  label: string;
  /** One sentence for non-HR readers: what it is / what to collect. */
  help: string;
  handling: DocHandling;
  access: DocAccess;
  requirement: DocRequirement;
  appliesTo?: Applicability;
  /** Several documents of this type are normal (e.g. one per training). */
  multiple?: boolean;
  /** The document expires; HR is warned before it lapses. */
  tracksExpiry?: boolean;
  /** Typical validity, used to suggest an expiry date from the issue date. */
  validityMonths?: number;
  /** Label for the per-document reference field (ID number, license number, consent version…). */
  referenceLabel?: string;
  /** Structured data kept elsewhere in the employee record for this item. */
  fieldsNote?: string;
  /** Retention after separation, in years. SAMPLE: confirm with the Firm before go-live. */
  retentionYears: number;
}


// ---------- Access rules ----------

export interface AccessContext {
  role: Role;
  /** The document belongs to the caller's own 201 file. */
  isSelf: boolean;
  /** The caller is the employee's direct manager. */
  isDirectManager: boolean;
}

/** May the caller open (view/download) documents of this type? */
export function canOpenDocument(access: DocAccess, ctx: AccessContext): boolean {
  const { role, isSelf, isDirectManager } = ctx;
  if (role === 'HR_ADMIN') return true;
  switch (access) {
    case 'GENERAL':
      return role === 'SYSTEM_ADMIN' || isSelf;
    case 'PAYROLL':
      return role === 'SYSTEM_ADMIN' || role === 'PAYROLL_ADMIN' || isSelf;
    case 'PERFORMANCE':
      return isSelf || (role === 'MANAGER' && isDirectManager);
    case 'RESTRICTED':
    case 'HEALTH':
      return false; // HR only; employees ask HR for a copy
  }
}

/** May the caller add or change documents of this type? The Super Admin as HR, except IDs and health papers (HR only). */
export function canManageDocument(access: DocAccess, role: Role): boolean {
  if (role === 'HR_ADMIN') return true;
  if (role === 'SYSTEM_ADMIN') return access !== 'RESTRICTED' && access !== 'HEALTH';
  return access === 'PAYROLL' && role === 'PAYROLL_ADMIN';
}

/** Roles that see every employee's 201 checklist (the "201 files" page). */
export const canReview201Files = (role: Role) => role === 'HR_ADMIN' || role === 'SYSTEM_ADMIN';


/** Days before expiry when HR starts seeing "Expiring soon". */
export const EXPIRY_WARNING_DAYS = 30;

export interface ChecklistEmployee {
  civilStatus: string | null;
  childrenCount: number;
  licenseType: string | null;
  hireDate: DateKey;
  separationDate: DateKey | null;
  /** Personal data sheet: address + emergency contact filled in. */
  personalDataComplete: boolean;
}

export interface ChecklistDoc {
  type: DocumentType;
  issuedOn: DateKey | null;
  expiresOn: DateKey | null;
  uploadedAt: string;
}

function applies(def: DocumentTypeDef, e: ChecklistEmployee): boolean {
  switch (def.requirement) {
    case 'REQUIRED':
      return true;
    case 'ON_SEPARATION':
      return e.separationDate !== null;
    case 'IF_APPLICABLE':
      switch (def.appliesTo) {
        case 'MARRIED':
          return e.civilStatus === 'MARRIED';
        case 'HAS_CHILDREN':
          return e.childrenCount > 0;
        case 'LICENSED':
          return !!e.licenseType;
        case 'PRIOR_EMPLOYER_THIS_YEAR':
          // Can't be known from the record alone: never forced; HR uploads it when it applies.
          return false;
        default:
          return false;
      }
    default:
      return false;
  }
}

/** Expiry status of one document on `today`. */
export function expiryStatus(
  expiresOn: DateKey | null,
  today: DateKey,
  warnDays = EXPIRY_WARNING_DAYS,
): 'VALID' | 'EXPIRING' | 'EXPIRED' {
  if (!expiresOn) return 'VALID';
  if (expiresOn < today) return 'EXPIRED';
  if (expiresOn <= addDays(today, warnDays)) return 'EXPIRING';
  return 'VALID';
}

